def is_supported(lang) -> bool:
    return lang in SUPPORTED


def t(key: str, lang: str | None = None) -> str:
    lang = lang if is_supported(lang) else DEFAULT_LANG
    table = TRANSLATIONS.get(lang, _ZH_CN)
    if key in table:
        return table[key]
    if key in _ZH_CN:
        return _ZH_CN[key]
    return key


